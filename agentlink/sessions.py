"""Devices, sessions and the four distinct liveness signals.

    device_heartbeat      the participant's machine reaches the server (sent by the local supervisor)
    supervisor_heartbeat  the supervisor's own loop is healthy (same request, flag `supervisor_ok`)
    session_heartbeat     a specific agent session (or sub-agent session) is alive
    execution_progress    the session reported *observable work* (tool calls, checkpoints, notes)

None of them implies the next one: a connected device says nothing about its agents, and a live
session says nothing about progress. Only progress can keep a task lease alive (see coordination.renew_task).

Session ids are generated by the server. A session always belongs to the authenticated agent; a
sub-agent session must name a live parent session of the same agent.
"""

from __future__ import annotations

import json
import secrets
from typing import Any

from . import validation as v
from .config import Settings
from .db import Database, Executor, Row
from .errors import Conflict, Forbidden, NotFound
from .events import emit, scoped_monitor
from .projects import default_project_id, membership, project_for
from .security import Principal, now_ms

SESSION_STATES = ("registered", "executing", "idle", "waiting")  # reported by the client
RUNTIMES = ("claude-code", "codex", "opencode", "generic", "synthetic", "human")
CAPS_MAX = 32


def _caps(value: Any) -> list[str]:
    return v.str_list(value, "capabilities", max_items=CAPS_MAX, max_len=64)


def session_out(r: Row, now: int, settings: Settings) -> dict[str, Any]:
    return {
        "id": r["id"],
        "agent": r["agent"],
        "owner": r["owner"] or r["agent"],
        "project": r["project"],
        "parent_id": r["parent_id"],
        "device": r["device"],
        "runtime": r["runtime"],
        "provider": r["provider"],
        "model": r["model"],
        "specialization": r["specialization"] or r["agent_specialization"] or "",
        "capabilities": json.loads(r["capabilities"]) if r["capabilities"] else [],
        "label": r["label"],
        "reported_state": r["state"],
        "status": derived_status(r, now, settings),
        "created_at": r["created_at"],
        "last_heartbeat_at": r["last_heartbeat_at"],
        "last_progress_at": r["last_progress_at"],
        "progress_note": r["progress_note"],
        "ended_at": r["ended_at"],
        "end_reason": r["end_reason"],
    }


def derived_status(r: Row, now: int, settings: Settings) -> str:
    """terminated > offline > stalled > reported state. Pure function of persisted fields + server clock."""
    if r["ended_at"] is not None:
        return "terminated"
    if now - int(r["last_heartbeat_at"]) > settings.session_ttl * 1000:
        return "offline"
    if r["state"] == "executing":
        last = int(r["last_progress_at"] or r["created_at"])
        if now - last > settings.stall_after * 1000:
            return "stalled"
    return str(r["state"])


SESSION_SELECT = (
    "SELECT s.*, a.name AS agent, a.owner AS owner, a.specialization AS agent_specialization, "
    "pr.name AS project, d.name AS device FROM sessions s JOIN agents a ON a.id = s.agent_id "
    "JOIN projects pr ON pr.id = s.project_id LEFT JOIN devices d ON d.id = s.device_id "
)


def own_session(db: Executor, p: Principal, session_id: Any, *, live: bool = True) -> Row:
    """The caller's own session. Admins may act on any session (moderation), others only on theirs."""
    sid = v.text(session_id, "session_id", 64, required=True)
    row = db.one(f"{SESSION_SELECT} WHERE s.id = ?", (sid,))
    if row is None:
        raise NotFound(f"session '{sid}' not found")
    if int(row["agent_id"]) != p.agent_id and not p.is_admin:
        raise Forbidden("this session belongs to another agent")
    if live and row["ended_at"] is not None:
        raise Conflict(f"session '{sid}' has ended ({row['end_reason']})", reason="session_ended")
    return row


def _device_id(tx: Executor, p: Principal, name: str, owner: str) -> int | None:
    if not name:
        return None
    now = now_ms()
    row = tx.one(
        "INSERT INTO devices(owner, name, last_seen) VALUES (?, ?, ?) "
        "ON CONFLICT (owner, name) DO UPDATE SET last_seen = excluded.last_seen RETURNING id",
        (owner, name, now),
    )
    return int(row["id"]) if row else None


def register_session(db: Database, p: Principal, payload: dict[str, Any], settings: Settings) -> dict[str, Any]:
    p.require_writer()
    payload = v.obj(payload)
    if payload.get("project"):
        pr = project_for(db, p, payload["project"], write=True)
        pid = int(pr["id"])
    else:
        rows = db.query("SELECT project_id FROM project_members WHERE agent_id = ?", (p.agent_id,))
        pid = int(rows[0]["project_id"]) if len(rows) == 1 else default_project_id(db)
        if not p.is_admin and membership(db, pid, p.agent_id) is None:
            raise Forbidden("specify a project you are a member of")
    runtime = v.choice(payload.get("runtime"), "runtime", RUNTIMES, default="generic")
    provider = v.text(payload.get("provider"), "provider", 64)
    model = v.text(payload.get("model"), "model", 120)
    spec = v.text(payload.get("specialization"), "specialization", 64).strip().lower()
    label = v.text(payload.get("label"), "label", 120)
    caps = _caps(payload.get("capabilities"))
    device = v.text(payload.get("device"), "device", 120).strip()
    parent = payload.get("parent_session_id")
    now = now_ms()
    with db.transaction() as tx:
        agent = tx.one("SELECT owner FROM agents WHERE id = ?", (p.agent_id,))
        owner = (agent or {}).get("owner") or p.name
        parent_row = None
        if parent:
            parent_row = own_session(tx, p, parent)
            if int(parent_row["agent_id"]) != p.agent_id:
                raise Forbidden("a sub-agent session must hang from a session of the same agent")
            pid = int(parent_row["project_id"])
        sid = "ses_" + secrets.token_urlsafe(12)
        tx.execute(
            "INSERT INTO sessions(id, agent_id, project_id, parent_id, device_id, runtime, provider, model, "
            "specialization, capabilities, label, state, created_at, last_heartbeat_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'registered', ?, ?)",
            (
                sid,
                p.agent_id,
                pid,
                parent_row["id"] if parent_row else None,
                _device_id(tx, p, device, owner) if device else (parent_row or {}).get("device_id"),
                runtime,
                provider,
                model,
                spec,
                json.dumps(caps) if caps else None,
                label,
                now,
                now,
            ),
        )
        emit(
            tx,
            "session.registered",
            project_id=pid,
            actor_id=p.agent_id,
            session_id=sid,
            data={"runtime": runtime, "parent_id": parent_row["id"] if parent_row else None, "specialization": spec},
        )
        row = tx.one(f"{SESSION_SELECT} WHERE s.id = ?", (sid,))
    assert row is not None
    return session_out(row, now, settings)


def heartbeat_session(
    db: Database, p: Principal, session_id: str, payload: dict[str, Any], settings: Settings
) -> dict[str, Any]:
    """Session liveness, plus progress when the client has evidence of work (`progress: true` or a note)."""
    payload = v.obj(payload)
    state = v.choice(payload.get("state"), "state", SESSION_STATES, default=None) if payload.get("state") else None
    note = v.text(payload.get("progress_note"), "progress_note", 300)
    progress = bool(payload.get("progress")) or bool(note)
    now = now_ms()
    with db.transaction() as tx:
        s = own_session(tx, p, session_id)
        if not p.is_admin and membership(tx, int(s["project_id"]), p.agent_id) is None:
            from .recovery import terminate_session

            terminate_session(tx, s, "no longer a project member", "session.ended", p.agent_id)
            ended = True
        else:
            ended = False
    if ended:  # committed above; then refuse like any ended session
        raise Conflict(f"session {session_id} has ended: not a member of its project", reason="session_ended")
    with db.transaction() as tx:
        s = own_session(tx, p, session_id)
        if derived_status(s, now, settings) == "offline":
            # Expired but not yet reconciled: the reconciler decides; a late heartbeat revives liveness only.
            pass
        sets = ["last_heartbeat_at = ?"]
        params: list[Any] = [now]
        if state:
            sets.append("state = ?")
            params.append(state)
        if progress:
            sets.append("last_progress_at = ?")
            params.append(now)
            if note:
                sets.append("progress_note = ?")
                params.append(note)
        if progress and s["stalled_since"] is not None:
            sets.append("stalled_since = NULL")
            emit(tx, "session.resumed", project_id=int(s["project_id"]), actor_id=p.agent_id, session_id=s["id"])
        if (state or s["state"]) != "executing" and s["stalled_since"] is not None and not progress:
            sets.append("stalled_since = NULL")
        tx.execute(f"UPDATE sessions SET {', '.join(sets)} WHERE id = ?", (*params, s["id"]))
        if progress:  # progress of the session is progress of the tasks it holds
            tx.execute(
                "UPDATE tasks SET last_progress_at = ? WHERE assignee_session = ? AND lease_expires_at > ?",
                (now, s["id"], now),
            )
        from .coordinator import renew_on_heartbeat

        coord = renew_on_heartbeat(tx, s, now, settings)
        row = tx.one(f"{SESSION_SELECT} WHERE s.id = ?", (s["id"],))
    assert row is not None
    out = session_out(row, now, settings)
    out["coordinator"] = coord
    out["held_tasks"] = db.query(
        "SELECT id, lease_epoch, lease_expires_at, status FROM tasks WHERE assignee_session = ?", (s["id"],)
    )
    return out


def end_session(
    db: Database, p: Principal, session_id: str, payload: dict[str, Any], settings: Settings
) -> dict[str, Any]:
    payload = v.obj(payload or {})
    reason = v.text(payload.get("reason"), "reason", 200) or "ended"
    from .recovery import terminate_session

    with db.transaction() as tx:
        s = own_session(tx, p, session_id)
        n = terminate_session(tx, s, reason, "session.ended", p.agent_id)
    return {"ended": session_id, "reason": reason, "sessions_ended": n}


def device_heartbeat(db: Database, p: Principal, payload: dict[str, Any]) -> dict[str, Any]:
    """Device + supervisor liveness. Deliberately does NOT touch sessions or task leases."""
    p.require_writer()
    payload = v.obj(payload)
    name = v.text(payload.get("device"), "device", 120, required=True).strip()
    version = v.text(payload.get("supervisor_version"), "supervisor_version", 40)
    ok = bool(payload.get("supervisor_ok", True))
    now = now_ms()
    with db.transaction() as tx:
        agent = tx.one("SELECT owner FROM agents WHERE id = ?", (p.agent_id,))
        owner = (agent or {}).get("owner") or p.name
        tx.execute(
            "INSERT INTO devices(owner, name, last_seen, supervisor_seen, supervisor_version) VALUES (?, ?, ?, ?, ?) "
            "ON CONFLICT (owner, name) DO UPDATE SET last_seen = excluded.last_seen, "
            "supervisor_seen = COALESCE(excluded.supervisor_seen, devices.supervisor_seen), "
            "supervisor_version = excluded.supervisor_version",
            (owner, name, now, now if ok else None, version),
        )
    return {"device": name, "owner": owner, "supervisor_ok": ok, "server_time": now}


def list_sessions(db: Database, p: Principal, q: dict[str, Any], settings: Settings) -> list[dict[str, Any]]:
    where, params = "1 = 1", []
    if q.get("project"):
        pr = project_for(db, p, q["project"])
        where += " AND s.project_id = ?"
        params.append(pr["id"])
    elif not (p.is_admin or (p.role == "monitor" and not scoped_monitor(db, p))):
        where += " AND s.project_id IN (SELECT project_id FROM project_members WHERE agent_id = ?)"
        params.append(p.agent_id)
    if not q.get("all"):
        where += " AND s.ended_at IS NULL"
    if q.get("mine"):
        where += " AND s.agent_id = ?"
        params.append(p.agent_id)
    rows = db.query(f"{SESSION_SELECT} WHERE {where} ORDER BY s.created_at LIMIT 500", tuple(params))
    now = now_ms()
    return [session_out(r, now, settings) for r in rows]


def list_devices(db: Database, p: Principal) -> list[dict[str, Any]]:
    now = now_ms()
    rows = db.query(
        "SELECT owner, name, last_seen, supervisor_seen, supervisor_version FROM devices ORDER BY owner, name"
    )
    if not (p.is_admin or p.role == "monitor"):
        me = db.one("SELECT owner FROM agents WHERE id = ?", (p.agent_id,))
        owner = (me or {}).get("owner") or p.name
        rows = [r for r in rows if r["owner"] == owner]
    return [{**r, "age_s": (now - int(r["last_seen"])) // 1000} for r in rows]
